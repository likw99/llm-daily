@dataclass
class ArchivedIssue:
    day: date
    en_path: Path
    zh_path: Optional[Path]
    meta: dict

    @property
    def slug(self) -> str:
        return self.day.isoformat()

    @property
    def title(self) -> str:
        return f"LLM Daily: {self.day.strftime('%B %d, %Y')}"


def find_issues(archive_dir: Path) -> List[ArchivedIssue]:
    """All English issues in the archive, newest first."""
    issues = []
    for path in archive_dir.rglob("*.md"):
        match = _DATE_FILE.match(path.name)
        if not match:
            continue
        day = date.fromisoformat(match.group(1))
        zh = path.with_name(f"{match.group(1)}.zh.md")
        meta_path = path.with_name(f"{match.group(1)}.json")
        meta = json.loads(meta_path.read_text(encoding="utf-8")) if meta_path.exists() else {}
        issues.append(ArchivedIssue(day, path, zh if zh.exists() else None, meta))
    return sorted(issues, key=lambda i: i.day, reverse=True)


def _page(title: str, body: str, base: str, lang: str = "en") -> str:
    return f"""<!doctype html>
<html lang="{lang}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{html.escape(title)}</title>
<link rel="alternate" type="application/atom+xml" title="{SITE_TITLE}" href="{base}feed.xml">
<style>{CSS}</style>
</head>
<body>
<main>
<header class="site">
<a class="home" href="{base}index.html">{SITE_TITLE}</a>
<p>{SITE_TAGLINE}</p>
<nav class="links"><a href="{base}feed.xml">RSS</a><a href="{REPO_URL}">Source code</a></nav>
</header>
{body}
<footer>Every item links to its source. Generated by <a href="{REPO_URL}">llm-daily</a>.</footer>
</main>
</body>
</html>
"""


def _strip_top_title(md: str) -> str:
    """Drop the masthead lines; the page header already names the newsletter."""
    lines = md.splitlines()
    while lines and (lines[0].startswith("# 🔍") or lines[0].startswith("## Your Daily Briefing")
                     or lines[0].startswith("## 大模型每日简报") or _BOLD_DATE.match(lines[0].strip())
                     or not lines[0].strip()):
        lines.pop(0)
    return "\n".join(lines)


def _atom_time(day: date) -> str:
    return datetime(day.year, day.month, day.day, 2, 0, tzinfo=timezone.utc).isoformat().replace("+00:00", "Z")


def build_feed(issues: List[ArchivedIssue], base_url: str, zh: bool = False) -> str:
    chosen = [i for i in issues if (i.zh_path if zh else i.en_path)][:FEED_SIZE]
    feed_name = "feed-zh.xml" if zh else "feed.xml"
    updated = _atom_time(chosen[0].day) if chosen else _atom_time(date.today())
    entries = []
    for issue in chosen:
        suffix = ".zh" if zh else ""
        url = f"{base_url}issues/{issue.slug}{suffix}.html"
        md = (issue.zh_path if zh else issue.en_path).read_text(encoding="utf-8")
        entries.append(f"""  <entry>
    <title>{html.escape(issue.title)}</title>
    <link href="{html.escape(url)}"/>
    <id>{html.escape(url)}</id>
    <updated>{_atom_time(issue.day)}</updated>
    <content type="html">{html.escape(to_html(_strip_top_title(md)))}</content>
  </entry>""")
    title = f"{SITE_TITLE} (中文)" if zh else SITE_TITLE
    return f"""<?xml version="1.0" encoding="utf-8"?>
<feed xmlns="http://www.w3.org/2005/Atom">
  <title>{html.escape(title)}</title>
  <subtitle>{html.escape(SITE_TAGLINE)}</subtitle>
  <link href="{html.escape(base_url)}"/>
  <link rel="self" href="{html.escape(base_url + feed_name)}"/>
  <id>{html.escape(base_url)}</id>
  <updated>{updated}</updated>
  <author><name>LLM Daily</name></author>
{chr(10).join(entries)}
</feed>
"""


def build_site(archive_dir: Path, out_dir: Path, base_url: str = "") -> int:
    """Write index.html, one page per issue (and Chinese edition) and Atom feeds. Returns the issue count."""
    base = base_url.rstrip("/") + "/" if base_url else ""
    issues = find_issues(archive_dir)
    (out_dir / "issues").mkdir(parents=True, exist_ok=True)

    for issue in issues:
        page_base = "../" if not base else base
        zh_link = f' · <a href="{issue.slug}.zh.html">中文</a>' if issue.zh_path else ""
        body = (f'<p class="lang">{issue.day.strftime("%B %d, %Y")}{zh_link}</p>\n'
                f'<article>{to_html(_strip_top_title(issue.en_path.read_text(encoding="utf-8")))}</article>')
        (out_dir / "issues" / f"{issue.slug}.html").write_text(_page(issue.title, body, page_base), encoding="utf-8")
        if issue.zh_path:
            body_zh = (f'<p class="lang">{issue.slug} · <a href="{issue.slug}.html">English</a></p>\n'
                       f'<article>{to_html(_strip_top_title(issue.zh_path.read_text(encoding="utf-8")))}</article>')
            (out_dir / "issues" / f"{issue.slug}.zh.html").write_text(
                _page(f"LLM Daily 大模型日报 {issue.slug}", body_zh, page_base, lang="zh-CN"), encoding="utf-8")

    rows = []
    for issue in issues:
        zh = f' · <a href="issues/{issue.slug}.zh.html">中文</a>' if issue.zh_path else ""
        rows.append(f'<li><span class="date">{issue.slug}</span>'
                    f'<a href="issues/{issue.slug}.html">{html.escape(issue.title)}</a>{zh}</li>')
    count = f"<p>{len(issues)} issues so far.</p>" if issues else "<p>No issues yet.</p>"
    index_body = f"{count}\n<ul class=\"issues\">\n" + "\n".join(rows) + "\n</ul>"
    (out_dir / "index.html").write_text(_page(SITE_TITLE, index_body, base), encoding="utf-8")

    (out_dir / "feed.xml").write_text(build_feed(issues, base), encoding="utf-8")
    if any(i.zh_path for i in issues):
        (out_dir / "feed-zh.xml").write_text(build_feed(issues, base, zh=True), encoding="utf-8")
    (out_dir / ".nojekyll").write_text("", encoding="utf-8")
    return len(issues)


def main(argv=None) -> int:
    root = get_project_root()
    parser = argparse.ArgumentParser(prog="llm-daily-site", description="Build the static web archive and RSS feed")
    parser.add_argument("--archive", default=str(root / "archive"), help="Archive folder (default: archive/)")
    parser.add_argument("--out", default=str(root / "site"), help="Output folder (default: site/)")
    parser.add_argument("--base-url", default=os.environ.get("LLMDAILY_SITE_URL", ""),
                        help="Public base URL, used for feed links. Overrides LLMDAILY_SITE_URL")
    args = parser.parse_args(argv)
    count = build_site(Path(args.archive), Path(args.out), args.base_url)
    print(f"Built {count} issues into {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
