"""Build a static web archive and Atom feeds from archive/.

Usage:
    llm-daily-site [--archive archive] [--out site] [--base-url https://you.github.io/llm-daily/]
"""

import argparse
import html
import json
import os
import re
import sys
from dataclasses import dataclass
from datetime import date, datetime, timezone
from pathlib import Path
from typing import List, Optional

from .publishers.render import to_html
from .utils.common import get_project_root

SITE_TITLE = "LLM Daily"
SITE_TAGLINE = "An AI newsletter written each morning by an open-source agent"
REPO_URL = "https://github.com/likw99/llm-daily"
FEED_SIZE = 30
_DATE_FILE = re.compile(r"^(\d{4}-\d{2}-\d{2})\.md$")
_BOLD_DATE = re.compile(r"^\*\*[^*]+\d{4}[^*]*\*\*$")

